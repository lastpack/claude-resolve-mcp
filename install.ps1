# claude-resolve-mcp installer (Windows)
#   powershell -ExecutionPolicy Bypass -File install.ps1 [-Motion]
# - installs Python deps (uv)
# - generates bridge/start.lua (the loader you dofile() in Resolve's Lua console)
# - writes .mcp.json for Claude Code
# - -Motion: also installs Remotion (Node.js) for text/graphics overlays
param([switch]$Motion)
$ErrorActionPreference = "Stop"
$repo = $PSScriptRoot
$repoFwd = $repo -replace '\\', '/'

if (-not (Get-Command uv -ErrorAction SilentlyContinue)) {
    throw "uv not found. Install it: https://docs.astral.sh/uv/getting-started/installation/"
}
Push-Location $repo
uv sync
Pop-Location

New-Item -ItemType Directory -Force (Join-Path $repo "queue"), (Join-Path $repo "work") | Out-Null

# Loader for Resolve (machine-specific, gitignored): sets the repo root and runs the bridge
$loader = Join-Path $repo "bridge\start.lua"
$code = "-- claude-resolve-mcp loader (generated by install.ps1)`nRESOLVE_MCP_ROOT = [[$repoFwd]]`ndofile(RESOLVE_MCP_ROOT .. '/bridge/ResolveBridge.lua')`n"
[IO.File]::WriteAllText($loader, $code, (New-Object Text.UTF8Encoding $false))

# MCP config for Claude Code (project scope)
$mcp = @{ mcpServers = @{ "davinci-resolve" = @{ command = "uv"; args = @("run", "--directory", $repo, "resolve-mcp") } } }
[IO.File]::WriteAllText((Join-Path $repo ".mcp.json"), ($mcp | ConvertTo-Json -Depth 5), (New-Object Text.UTF8Encoding $false))

if ($Motion) {
    if (-not (Get-Command npm -ErrorAction SilentlyContinue)) { throw "Node.js/npm not found (needed for -Motion)" }
    Push-Location (Join-Path $repo "motion")
    npm install --no-fund --no-audit
    npm install-scripts approve esbuild 2>$null
    npm rebuild esbuild
    Pop-Location
}

$loaderFwd = $loader -replace '\\', '/'
Write-Host ""
Write-Host "Done. Start the bridge once per Resolve launch (with a project open):" -ForegroundColor Green
Write-Host "  Workspace > Console, Lua tab, paste and press Enter:"
Write-Host "  dofile([[$loaderFwd]])" -ForegroundColor Yellow
Write-Host "Then open Claude Code in $repo"
